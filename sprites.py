CLEAR = -1


class Sprite:
    __slots__ = ('grid', 'w', 'h', 'px', 'py')

    def __init__(self, rows, px=None, py=None):
        self.grid = tuple(tuple(CLEAR if c == '.' else int(c, 16) for c in row)
                          for row in rows)
        self.h = len(self.grid)
        self.w = len(self.grid[0])
        self.px = self.w / 2 if px is None else px
        self.py = self.h / 2 if py is None else py


def recolor(swaps):
    return tuple(swaps.get(c, c) for c in range(16))


def cycle(color, steps):
    return tuple(recolor({color: c}) for c in steps)


